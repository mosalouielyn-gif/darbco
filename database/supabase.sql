CREATE TABLE inventory_categories (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code  VARCHAR(8)  NOT NULL UNIQUE,
  label VARCHAR(80) NOT NULL UNIQUE
);

